-- =====================================================================
--  V16 — Journal d'audit des actions du staff (ECART-63, DEC-02)
-- =====================================================================
--  Une ligne par action de la modération, de l'administration ou du
--  système : qui (acteur), quoi (action), sur quoi (cible), pourquoi
--  (motif), quand et d'où (adresse IP).
--
--  Pas de clé étrangère vers account : le journal doit survivre à la
--  suppression ou à l'anonymisation des comptes, acteurs comme cibles.
--  acteur_libelle fige l'email de l'acteur au moment de l'action.
--  Les lignes ne sont jamais modifiées ; la durée de conservation
--  (3 ans, adresse IP 90 jours : SFG §11.2) sera appliquée par la tâche
--  de purge de DEC-26.
-- =====================================================================

CREATE TABLE IF NOT EXISTS audit_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date            TIMESTAMP(6)  NOT NULL,
    acteur_id       UUID,
    acteur_libelle  VARCHAR(100)  NOT NULL,
    acteur_role     VARCHAR(30),
    action          VARCHAR(50)   NOT NULL,
    cible_type      VARCHAR(30)   NOT NULL,
    cible_id        VARCHAR(64)   NOT NULL,
    motif           VARCHAR(1000),
    adresse_ip      VARCHAR(45)
);

CREATE INDEX IF NOT EXISTS idx_audit_date   ON audit_event (date DESC);
CREATE INDEX IF NOT EXISTS idx_audit_cible  ON audit_event (cible_type, cible_id);
CREATE INDEX IF NOT EXISTS idx_audit_acteur ON audit_event (acteur_id);
