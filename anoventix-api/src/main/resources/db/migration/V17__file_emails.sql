-- =====================================================================
--  V17 — File d'envoi des emails (DEC-31, module 11 RG-11-01)
-- =====================================================================
--  Un email n'est plus envoyé directement : il est inscrit ici, dans la
--  transaction de l'action qui le déclenche (rien ne part si l'action est
--  annulée, rien n'est perdu si le serveur SMTP est indisponible), puis
--  envoyé par une tâche planifiée qui réessaie avec un délai croissant.
--
--  contenu_sensible : corps porteur d'un secret (lien d'activation, code de
--  réinitialisation, mot de passe temporaire). Il est effacé dès l'envoi
--  réussi ou l'abandon, pour qu'aucun secret ne reste en base.
-- =====================================================================

CREATE TABLE IF NOT EXISTS email_sortant (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinataire     VARCHAR(100)  NOT NULL,
    sujet            VARCHAR(200)  NOT NULL,
    corps_html       TEXT,
    contenu_sensible BOOLEAN       NOT NULL DEFAULT FALSE,
    statut           VARCHAR(20)   NOT NULL CHECK (statut IN ('EN_ATTENTE', 'ENVOYE', 'ABANDONNE')),
    tentatives       INTEGER       NOT NULL DEFAULT 0,
    prochain_essai   TIMESTAMP(6)  NOT NULL,
    derniere_erreur  VARCHAR(500),
    cree_le          TIMESTAMP(6)  NOT NULL,
    envoye_le        TIMESTAMP(6)
);

-- La tâche d'envoi ne lit que les emails en attente arrivés à échéance.
CREATE INDEX IF NOT EXISTS idx_email_sortant_a_envoyer
    ON email_sortant (prochain_essai) WHERE statut = 'EN_ATTENTE';
