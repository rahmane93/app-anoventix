-- =====================================================================
--  V8 — Licence annuelle (remplace crédits et boost)
-- =====================================================================
--  licence : clés générées par l'administrateur, activées par un
--  particulier ou un professionnel (1 an).
--  parametre_plateforme : réglages admin (licence.mode-actif).
--  Les tables credit_compte / credit_transaction et la colonne
--  annonce.boost_expiration ne sont plus utilisées mais sont conservées.
-- =====================================================================

CREATE TABLE IF NOT EXISTS parametre_plateforme (
    cle    VARCHAR(100) PRIMARY KEY,
    valeur VARCHAR(255) NOT NULL
);

-- Sur une base vierge, account n'existe pas encore : Hibernate (ddl-auto=update)
-- créera licence ensuite, la migration est donc sans effet.
DO $$
BEGIN
    IF to_regclass('account') IS NOT NULL THEN
        CREATE TABLE IF NOT EXISTS licence (
            id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            cle        VARCHAR(32)  NOT NULL UNIQUE,
            type       VARCHAR(20)  NOT NULL CHECK (type IN ('PARTICULIER', 'PROFESSIONNEL')),
            owner_id   UUID REFERENCES account(id),
            date_debut DATE,
            date_fin   DATE,
            created_at TIMESTAMP(6) NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_licence_owner ON licence(owner_id);
    END IF;
END $$;
